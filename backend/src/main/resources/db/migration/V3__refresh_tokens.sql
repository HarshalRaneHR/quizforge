-- V3: refresh tokens for long-lived sessions (rotated on every use; only the SHA-256 hash is stored).

CREATE TABLE refresh_tokens (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash    VARCHAR(64)  NOT NULL,
    family_id     UUID         NOT NULL,   -- all tokens from one login share a family
    expires_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    revoked_at    TIMESTAMP(6) WITH TIME ZONE,
    revoke_reason VARCHAR(20),
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_refresh_tokens_hash UNIQUE (token_hash),
    CONSTRAINT ck_refresh_tokens_reason CHECK (revoke_reason IN ('ROTATED', 'LOGOUT', 'REUSE_DETECTED'))
);
CREATE INDEX idx_refresh_tokens_family ON refresh_tokens (family_id);
CREATE INDEX idx_refresh_tokens_expires ON refresh_tokens (expires_at);
