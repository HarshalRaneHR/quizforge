-- V4: multiple question types.
-- Questions get a type plus two JSONB documents: `content` (shown to learners) and `answer_key`
-- (never sent before grading). Existing multiple-choice questions are converted in place.

ALTER TABLE question
    ADD COLUMN type       VARCHAR(30),
    ADD COLUMN difficulty VARCHAR(10),
    ADD COLUMN points     INTEGER,
    ADD COLUMN position   INTEGER,
    ADD COLUMN content    JSONB,
    ADD COLUMN answer_key JSONB;

UPDATE question q
SET type       = 'SINGLE_CHOICE',
    difficulty = 'MEDIUM',
    points     = 1,
    content    = jsonb_build_object('options', (
                     SELECT COALESCE(jsonb_agg(o.option_text ORDER BY o.option_index), '[]'::jsonb)
                     FROM question_options o
                     WHERE o.question_id = q.id)),
    answer_key = jsonb_build_object('correctIndex', q.correct_index);

UPDATE question q
SET position = ordered.rn - 1
FROM (SELECT id, ROW_NUMBER() OVER (PARTITION BY quiz_id ORDER BY id) AS rn FROM question) ordered
WHERE ordered.id = q.id;

ALTER TABLE question
    ALTER COLUMN type SET NOT NULL,
    ALTER COLUMN difficulty SET NOT NULL,
    ALTER COLUMN points SET NOT NULL,
    ALTER COLUMN position SET NOT NULL,
    ALTER COLUMN content SET NOT NULL,
    ALTER COLUMN answer_key SET NOT NULL,
    DROP COLUMN correct_index,
    ADD CONSTRAINT ck_question_type CHECK (type IN
        ('SINGLE_CHOICE', 'MULTIPLE_CHOICE', 'TRUE_FALSE', 'FILL_BLANK', 'NUMERIC', 'ORDERING', 'MATCHING')),
    ADD CONSTRAINT ck_question_difficulty CHECK (difficulty IN ('EASY', 'MEDIUM', 'HARD')),
    ADD CONSTRAINT ck_question_points CHECK (points BETWEEN 1 AND 10);

DROP TABLE question_options;

-- Quizzes: total points for display/percentages.
ALTER TABLE quiz ADD COLUMN total_points INTEGER NOT NULL DEFAULT 0;
UPDATE quiz SET total_points = question_count;

-- Attempts: scores can now be fractional (partial credit).
ALTER TABLE attempt RENAME COLUMN total TO max_score;
ALTER TABLE attempt
    ALTER COLUMN score TYPE DOUBLE PRECISION,
    ALTER COLUMN max_score TYPE DOUBLE PRECISION;

-- Every answer is kept: enables reviewing attempts and per-question analytics later.
CREATE TABLE attempt_answer (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id     BIGINT           NOT NULL REFERENCES attempt (id) ON DELETE CASCADE,
    question_id    BIGINT           NOT NULL REFERENCES question (id) ON DELETE CASCADE,
    response       JSONB,
    points_awarded DOUBLE PRECISION NOT NULL,
    max_points     DOUBLE PRECISION NOT NULL,
    correct        BOOLEAN          NOT NULL
);
CREATE INDEX idx_attempt_answer_attempt ON attempt_answer (attempt_id);
CREATE INDEX idx_attempt_answer_question ON attempt_answer (question_id);
