-- V7: classrooms (join by code) and quiz assignments with optional due dates.

CREATE TABLE classroom (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id    BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    name        VARCHAR(120) NOT NULL,
    description TEXT,
    join_code   VARCHAR(12)  NOT NULL,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_classroom_join_code UNIQUE (join_code)
);
CREATE INDEX idx_classroom_owner ON classroom (owner_id);

CREATE TABLE classroom_member (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    classroom_id BIGINT NOT NULL REFERENCES classroom (id) ON DELETE CASCADE,
    user_id      BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    joined_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_classroom_member UNIQUE (classroom_id, user_id)
);
CREATE INDEX idx_classroom_member_user ON classroom_member (user_id);

CREATE TABLE assignment (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    classroom_id BIGINT NOT NULL REFERENCES classroom (id) ON DELETE CASCADE,
    quiz_id      BIGINT NOT NULL REFERENCES quiz (id) ON DELETE CASCADE,
    due_at       TIMESTAMP(6) WITH TIME ZONE,
    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_assignment_quiz UNIQUE (classroom_id, quiz_id)
);
CREATE INDEX idx_assignment_classroom ON assignment (classroom_id);
