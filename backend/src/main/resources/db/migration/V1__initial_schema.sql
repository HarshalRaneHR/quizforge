-- V1: initial QuizForge schema (users, quizzes, questions, attempts).
-- Never edit a migration after it has run; add a new V<n>__ file instead.

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    created_at    TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT ck_users_role CHECK (role IN ('USER', 'ADMIN'))
);

CREATE TABLE quiz (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title          VARCHAR(255) NOT NULL,
    source_text    TEXT         NOT NULL,
    question_count INTEGER      NOT NULL,
    owner_id       BIGINT       NOT NULL REFERENCES users (id),
    created_at     TIMESTAMP(6) WITH TIME ZONE
);
CREATE INDEX idx_quiz_owner ON quiz (owner_id);

CREATE TABLE question (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id       BIGINT  NOT NULL REFERENCES quiz (id) ON DELETE CASCADE,
    prompt        TEXT    NOT NULL,
    correct_index INTEGER NOT NULL,
    explanation   TEXT
);
CREATE INDEX idx_question_quiz ON question (quiz_id);

CREATE TABLE question_options (
    question_id  BIGINT  NOT NULL REFERENCES question (id) ON DELETE CASCADE,
    option_index INTEGER NOT NULL,
    option_text  TEXT    NOT NULL,
    PRIMARY KEY (question_id, option_index)
);

CREATE TABLE attempt (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT  NOT NULL REFERENCES users (id),
    quiz_id    BIGINT  NOT NULL REFERENCES quiz (id),
    score      INTEGER NOT NULL,
    total      INTEGER NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE
);
CREATE INDEX idx_attempt_user_created ON attempt (user_id, created_at DESC);
CREATE INDEX idx_attempt_quiz ON attempt (quiz_id);
